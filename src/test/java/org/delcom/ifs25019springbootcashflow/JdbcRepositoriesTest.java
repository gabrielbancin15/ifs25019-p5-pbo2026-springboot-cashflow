package org.delcom.ifs25019springbootcashflow;

import org.delcom.ifs25019springbootcashflow.adapter.repository.JdbcTransactionRepository;
import org.delcom.ifs25019springbootcashflow.adapter.repository.JdbcUserRepository;
import org.delcom.ifs25019springbootcashflow.domain.*;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.JdbcTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;
import java.time.LocalDateTime;
import static org.junit.jupiter.api.Assertions.*;

@JdbcTest
@ActiveProfiles("test")
@Import({JdbcUserRepository.class,JdbcTransactionRepository.class})
class JdbcRepositoriesTest {
 @Autowired JdbcTemplate jdbc;
 @Autowired JdbcUserRepository users;
 @Autowired JdbcTransactionRepository transactions;
 @BeforeEach void schema(){
  jdbc.execute("DROP TABLE IF EXISTS transactions");jdbc.execute("DROP TABLE IF EXISTS app_users");
  jdbc.execute("CREATE TABLE app_users(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,username VARCHAR(100) UNIQUE NOT NULL,password_hash VARCHAR(64) NOT NULL,full_name VARCHAR(200) NOT NULL,role VARCHAR(20) NOT NULL,photo_path VARCHAR(500))");
  jdbc.execute("CREATE TABLE transactions(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES app_users(id),description VARCHAR(500) NOT NULL,amount BIGINT NOT NULL,type VARCHAR(20) NOT NULL,proof_path VARCHAR(500),created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
 }
 @Test void jdbcRepositoriesPersistAndReadRecords(){
  User user=users.save(new User(null,"tester","hash","Tester",Role.USER,null));
  assertEquals("tester",users.findByUsername("tester").orElseThrow().username());
  Transaction tx=transactions.save(new Transaction(null,user.id(),"Gaji",1200,TransactionType.INCOME,null,LocalDateTime.now()));
  assertEquals(1,transactions.findByUserId(user.id()).size());
  assertEquals(1200,transactions.findById(tx.id()).orElseThrow().amount());
  assertEquals(1,transactions.findAll().size());
  transactions.save(new Transaction(tx.id(),user.id(),"Gaji diperbarui",1500,TransactionType.INCOME,null,tx.createdAt()));
  assertEquals("Gaji diperbarui",transactions.findById(tx.id()).orElseThrow().description());
  transactions.deleteById(tx.id());
  assertTrue(transactions.findByUserId(user.id()).isEmpty());
  assertEquals(1,users.findAll().size());
  users.save(new User(user.id(),user.username(),user.passwordHash(),"Nama Baru",user.role(),"/uploads/a.png"));
  assertEquals("Nama Baru",users.findById(user.id()).orElseThrow().fullName());
 }
}
